#!/usr/bin/env python3
"""Regenerates the formatting bar's outlines from their SVGs.

Reads docs/design/components/icons/toolbar/<name>.svg — Material Symbols
Outlined at weight 300 (Apache-2.0, github.com/google/material-design-icons)
or a hand-drawn replacement exported from Penpot — and writes
src/packages/ui/lib/src/widgets/tom_toolbar_outlines.dart.

Replacing an icon is one file: drop the new <name>.svg over the old one
(one <path>, a viewBox) and run this script.
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "docs/design/components/icons/toolbar"
TARGET = ROOT / "src/packages/ui/lib/src/widgets/tom_toolbar_outlines.dart"

# File name -> (TomGlyphEnum member, the Material Symbols name it began as).
GLYPHS = {
    "undo": ("undo", "undo"),
    "redo": ("redo", "redo"),
    "heading": ("heading", "title"),
    "bold": ("bold", "format_bold"),
    "italic": ("italic", "format_italic"),
    "strikethrough": ("strikethrough", "strikethrough_s"),
    "list": ("list", "format_list_bulleted"),
    "ordered-list": ("orderedList", "format_list_numbered"),
    "task-list": ("taskList", "checklist"),
    "quote": ("quote", "format_quote"),
    "code": ("code", "code"),
    "table": ("table", "table"),
    "rule": ("rule", "horizontal_rule"),
    "link": ("link", "link"),
    "image": ("image", "image"),
    "footnote": ("footnote", "superscript"),
    "alert": ("alert", "warning"),
}


def number(text):
    value = float(text)
    return str(int(value)) if value == int(value) else repr(value)


def chunks(text, width=64):
    return [text[i : i + width] for i in range(0, len(text), width)]


def entry(name):
    member, origin = GLYPHS[name]
    svg = (SOURCE / f"{name}.svg").read_text()
    view_box = re.search(r'viewBox="([^"]+)"', svg)
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
    if not view_box or len(paths) != 1:
        sys.exit(f"{name}.svg: expected one viewBox and exactly one <path>")
    left, top, width, height = (number(v) for v in view_box.group(1).split())
    lines = [f"  TomGlyphEnum.{member}: TomOutline(  // {origin}"]
    lines.append(f"    left: {left},")
    lines.append(f"    top: {top},")
    lines.append(f"    width: {width},")
    lines.append(f"    height: {height},")
    parts = chunks(paths[0])
    lines.append("    pathData:")
    for i, part in enumerate(parts):
        end = "," if i == len(parts) - 1 else ""
        lines.append(f"        '{part}'{end}")
    lines.append("  ),")
    return "\n".join(lines)


def main():
    body = "\n".join(entry(name) for name in GLYPHS)
    TARGET.write_text(
        "// GENERATED by docs/design/tools/toolbar_outlines.py from\n"
        "// docs/design/components/icons/toolbar/*.svg — do not edit by hand.\n"
        "/// The formatting bar's seventeen outlines.\n"
        "library;\n\n"
        "import 'package:tom_ui/src/widgets/tom_glyph_widget.dart';\n"
        "import 'package:tom_ui/src/widgets/tom_outline.dart';\n\n"
        "/// One outline per toolbar glyph: Material Symbols Outlined at weight\n"
        "/// 300, or the hand-drawn SVG that replaced it.\n"
        "const Map<TomGlyphEnum, TomOutline> tomToolbarOutlines =\n"
        "    <TomGlyphEnum, TomOutline>{\n" + body + "\n};\n"
    )
    subprocess.run(["dart", "format", str(TARGET)], check=True)


if __name__ == "__main__":
    main()
